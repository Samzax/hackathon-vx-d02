-- Modelo de dados da Mitra no Postgres (API e AWS RDS).
-- Mesmas tabelas e colunas de schema.sql (SQLite); tests/test_banco.py confere que não divergem.
-- Texto com COLLATE "C": ordena códigos (B1, OB-01, R95-03) igual ao SQLite, em qualquer locale do servidor.
-- Datas ficam em texto AAAA-MM-DD / AAAA-MM-DD HH:MM:SS (UTC), como no SQLite: o domínio compara strings.

CREATE TABLE IF NOT EXISTS empresa (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome              TEXT COLLATE "C" NOT NULL UNIQUE,
    ficticia          INTEGER NOT NULL DEFAULT 1 CHECK (ficticia IN (0, 1)),
    monitorado_desde  TEXT COLLATE "C",
    origem            TEXT COLLATE "C"
);

CREATE TABLE IF NOT EXISTS ativo (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id   BIGINT NOT NULL REFERENCES empresa(id),
    tipo         TEXT COLLATE "C" NOT NULL,
    codigo       TEXT COLLATE "C" NOT NULL,
    nome         TEXT COLLATE "C" NOT NULL,
    atributos    TEXT COLLATE "C" NOT NULL DEFAULT '{}' CHECK ((atributos::jsonb) IS NOT NULL),
    responsavel  TEXT COLLATE "C",
    unidade      TEXT COLLATE "C",
    UNIQUE (empresa_id, codigo)
);

CREATE TABLE IF NOT EXISTS ato (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fonte          TEXT COLLATE "C" NOT NULL,
    identificador  TEXT COLLATE "C" NOT NULL UNIQUE,
    titulo         TEXT COLLATE "C" NOT NULL,
    ementa         TEXT COLLATE "C",
    publicado_em   TEXT COLLATE "C",
    url            TEXT COLLATE "C",
    texto          TEXT COLLATE "C",
    sha256         TEXT COLLATE "C"
);

-- O código é único por empresa (índice obrigacao_empresa_codigo, no fim), não global.
CREATE TABLE IF NOT EXISTS obrigacao (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo      TEXT COLLATE "C" NOT NULL,
    tipo_ativo  TEXT COLLATE "C" NOT NULL,
    norma       TEXT COLLATE "C",
    area        TEXT COLLATE "C",
    empresa     TEXT COLLATE "C"
);

CREATE TABLE IF NOT EXISTS obrigacao_versao (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    obrigacao_id    BIGINT NOT NULL REFERENCES obrigacao(id),
    versao          INTEGER NOT NULL,
    titulo          TEXT COLLATE "C" NOT NULL,
    artigo          TEXT COLLATE "C" NOT NULL,
    aplica_se_a     TEXT COLLATE "C" NOT NULL,
    regra           TEXT COLLATE "C" NOT NULL,
    periodicidade   TEXT COLLATE "C",
    agenda          TEXT COLLATE "C" NOT NULL DEFAULT 'evento',
    prazo           TEXT COLLATE "C",
    vigencia_desde  TEXT COLLATE "C",
    vigencia_ate    TEXT COLLATE "C",
    responsavel     TEXT COLLATE "C",
    evidencia       TEXT COLLATE "C",
    fonte           TEXT COLLATE "C",
    ato_id          BIGINT REFERENCES ato(id),
    trecho          TEXT COLLATE "C",
    status          TEXT COLLATE "C" NOT NULL CHECK (status IN ('vigente', 'pendente', 'substituida', 'rejeitada')),
    criada_em       TEXT COLLATE "C" NOT NULL DEFAULT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'),
    decidida_por    TEXT COLLATE "C",
    decidida_em     TEXT COLLATE "C",
    correcao        TEXT COLLATE "C",
    UNIQUE (obrigacao_id, versao)
);

CREATE UNIQUE INDEX IF NOT EXISTS uma_vigente
    ON obrigacao_versao(obrigacao_id) WHERE status = 'vigente';
CREATE UNIQUE INDEX IF NOT EXISTS uma_pendente
    ON obrigacao_versao(obrigacao_id) WHERE status = 'pendente';

CREATE TABLE IF NOT EXISTS evidencia (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ativo_id      BIGINT NOT NULL REFERENCES ativo(id),
    obrigacao_id  BIGINT NOT NULL REFERENCES obrigacao(id),
    periodo       TEXT COLLATE "C" NOT NULL,
    arquivo       TEXT COLLATE "C",
    recebida_em   TEXT COLLATE "C" NOT NULL DEFAULT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'),
    extraido      TEXT COLLATE "C" CHECK (extraido IS NULL OR (extraido::jsonb) IS NOT NULL),
    UNIQUE (ativo_id, obrigacao_id, periodo)
);

CREATE TABLE IF NOT EXISTS acionamento (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ativo_id      BIGINT NOT NULL REFERENCES ativo(id),
    obrigacao_id  BIGINT NOT NULL REFERENCES obrigacao(id),
    dia           TEXT COLLATE "C" NOT NULL,
    prazo         TEXT COLLATE "C" NOT NULL,
    motivo        TEXT COLLATE "C" NOT NULL,
    origem        TEXT COLLATE "C",
    encerrado_em  TEXT COLLATE "C",
    UNIQUE (ativo_id, obrigacao_id, dia)
);

CREATE TABLE IF NOT EXISTS analise_ia (
    chave       TEXT COLLATE "C" PRIMARY KEY,
    tarefa      TEXT COLLATE "C" NOT NULL,
    provedor    TEXT COLLATE "C" NOT NULL,
    modelo      TEXT COLLATE "C" NOT NULL,
    resposta    TEXT COLLATE "C" NOT NULL,
    tokens_in   INTEGER,
    tokens_out  INTEGER,
    custo_usd   DOUBLE PRECISION,
    criada_em   TEXT COLLATE "C" NOT NULL DEFAULT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')
);

CREATE TABLE IF NOT EXISTS responsavel_obrigacao (
    ativo_id      BIGINT NOT NULL REFERENCES ativo(id),
    obrigacao_id  BIGINT NOT NULL REFERENCES obrigacao(id),
    responsavel   TEXT COLLATE "C" NOT NULL,
    PRIMARY KEY (ativo_id, obrigacao_id)
);

CREATE TABLE IF NOT EXISTS evento (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ativo_id      BIGINT NOT NULL REFERENCES ativo(id),
    obrigacao_id  BIGINT REFERENCES obrigacao(id),
    tipo          TEXT COLLATE "C" NOT NULL,
    texto         TEXT COLLATE "C" NOT NULL,
    por           TEXT COLLATE "C",
    em            TEXT COLLATE "C" NOT NULL DEFAULT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')
);

CREATE TABLE IF NOT EXISTS usuario (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email          TEXT COLLATE "C" NOT NULL UNIQUE,
    nome           TEXT COLLATE "C" NOT NULL,
    papel          TEXT COLLATE "C" NOT NULL CHECK (papel IN ('admin', 'diretoria', 'regulatorio', 'gestor')),
    area           TEXT COLLATE "C",
    senha          TEXT COLLATE "C",
    teste          INTEGER NOT NULL DEFAULT 0 CHECK (teste IN (0, 1)),
    ativa          INTEGER NOT NULL DEFAULT 1 CHECK (ativa IN (0, 1)),
    criado_por     TEXT COLLATE "C",
    criado_em      TEXT COLLATE "C" NOT NULL DEFAULT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'),
    ultimo_acesso  TEXT COLLATE "C",
    empresa        TEXT COLLATE "C",
    plataforma     INTEGER NOT NULL DEFAULT 0 CHECK (plataforma IN (0, 1)),
    trocar_senha   INTEGER NOT NULL DEFAULT 0 CHECK (trocar_senha IN (0, 1)),
    unidades       TEXT NOT NULL DEFAULT '[]'
);

-- Trilha de auditoria da API: toda escrita, com quem, quando, de onde e o resultado.
CREATE TABLE IF NOT EXISTS auditoria (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    em          TEXT COLLATE "C" NOT NULL DEFAULT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'),
    usuario     TEXT COLLATE "C",
    acao        TEXT COLLATE "C" NOT NULL,
    alvo        TEXT COLLATE "C",
    detalhe     TEXT COLLATE "C",
    request_id  TEXT COLLATE "C",
    resultado   TEXT COLLATE "C" NOT NULL,
    empresa     TEXT COLLATE "C"
);
CREATE INDEX IF NOT EXISTS auditoria_em ON auditoria(em);

-- Sessões da API (cookie HttpOnly): só o hash do token fica no banco.
CREATE TABLE IF NOT EXISTS sessao (
    token_hash  TEXT COLLATE "C" PRIMARY KEY,
    usuario_id  BIGINT NOT NULL REFERENCES usuario(id),
    criada_em   TEXT COLLATE "C" NOT NULL DEFAULT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'),
    expira_em   TEXT COLLATE "C" NOT NULL,
    visao       TEXT COLLATE "C"
);

-- Descoberta de normas (descoberta.py): normas já publicadas que podem valer para os ativos da carteira.
-- É trabalho da plataforma (curadoria Mitra), não de uma cliente: fica fora do "Recriar demo".
CREATE TABLE IF NOT EXISTS norma_candidata (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    chave         TEXT COLLATE "C" NOT NULL UNIQUE,
    jurisdicao    TEXT COLLATE "C" NOT NULL,
    fonte         TEXT COLLATE "C" NOT NULL,
    tipo          TEXT COLLATE "C" NOT NULL,
    numero        TEXT COLLATE "C" NOT NULL,
    ano           INTEGER NOT NULL,
    titulo        TEXT COLLATE "C" NOT NULL,
    ementa        TEXT COLLATE "C",
    indexacao     TEXT COLLATE "C",
    data          TEXT COLLATE "C",
    url           TEXT COLLATE "C",
    situacao      TEXT COLLATE "C",
    temas         TEXT COLLATE "C" NOT NULL DEFAULT '[]',
    triagem       TEXT COLLATE "C",
    status        TEXT COLLATE "C" NOT NULL DEFAULT 'nova'
                  CHECK (status IN ('nova', 'relevante', 'irrelevante', 'catalogada', 'aprovada', 'descartada')),
    decidida_por  TEXT COLLATE "C",
    decidida_em   TEXT COLLATE "C",
    nota          TEXT COLLATE "C",
    vista_em      TEXT COLLATE "C" NOT NULL DEFAULT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')
);

-- Até onde cada fonte foi lida: a cobertura só diz "verificada" do que foi lido de fato.
CREATE TABLE IF NOT EXISTS descoberta_busca (
    fonte       TEXT COLLATE "C" PRIMARY KEY,
    jurisdicao  TEXT COLLATE "C" NOT NULL,
    desde       INTEGER NOT NULL,
    ate         INTEGER NOT NULL,
    lidas       INTEGER NOT NULL,
    candidatas  INTEGER NOT NULL,
    em          TEXT COLLATE "C" NOT NULL
);

-- Vigência e alterações das normas federais, lidas da ficha da Câmara (mitra/vigencia.py).
CREATE TABLE IF NOT EXISTS norma_vigencia (
    chave         TEXT COLLATE "C" PRIMARY KEY,
    titulo        TEXT COLLATE "C" NOT NULL,
    ementa        TEXT,
    situacao      TEXT,
    revogada      INTEGER NOT NULL DEFAULT 0,
    relacoes      TEXT NOT NULL DEFAULT '[]',
    ficha_url     TEXT,
    texto_url     TEXT,
    original_url  TEXT,
    fonte         TEXT COLLATE "C" NOT NULL,
    lida_em       TEXT COLLATE "C" NOT NULL
);

-- Instanciação (mitra/instanciacao.py): levar uma cliente nova do zero até a torre funcionando.
-- Uma por empresa. O estado de cada etapa sai dos dados; quem fez o quê e quando fica em instanciacao_evento.
CREATE TABLE IF NOT EXISTS instanciacao (
    empresa_id    BIGINT PRIMARY KEY REFERENCES empresa(id),
    cnpj          TEXT COLLATE "C" UNIQUE,
    razao_social  TEXT COLLATE "C" NOT NULL,
    ufs           TEXT NOT NULL DEFAULT '[]',
    no_sigbm      INTEGER NOT NULL DEFAULT 0,
    criada_por    TEXT COLLATE "C" NOT NULL,
    criada_em     TEXT COLLATE "C" NOT NULL
);

CREATE TABLE IF NOT EXISTS instanciacao_evento (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id  BIGINT NOT NULL REFERENCES empresa(id),
    etapa       TEXT COLLATE "C" NOT NULL,
    acao        TEXT COLLATE "C" NOT NULL,
    detalhe     TEXT,
    por         TEXT COLLATE "C" NOT NULL,
    em          TEXT COLLATE "C" NOT NULL
);
CREATE INDEX IF NOT EXISTS instanciacao_evento_empresa ON instanciacao_evento(empresa_id, etapa);

-- A operação da empresa ("Mina Serra Azul", com as barragens e os equipamentos dela).
CREATE TABLE IF NOT EXISTS unidade (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id  BIGINT NOT NULL REFERENCES empresa(id),
    nome        TEXT COLLATE "C" NOT NULL,
    uf          TEXT COLLATE "C",
    municipio   TEXT COLLATE "C",
    criada_por  TEXT COLLATE "C",
    criada_em   TEXT COLLATE "C" NOT NULL,
    UNIQUE (empresa_id, nome)
);

-- A licença (LP, LI, LO, LAC, outorga, autorização) que a empresa enviou em PDF; o texto lido fica
-- aqui para o Python conferir o trecho literal de cada condicionante.
CREATE TABLE IF NOT EXISTS licenca (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id    BIGINT NOT NULL REFERENCES empresa(id),
    tipo          TEXT COLLATE "C" NOT NULL,
    numero        TEXT COLLATE "C" NOT NULL,
    orgao         TEXT COLLATE "C",
    emitida_em    TEXT COLLATE "C",
    validade      TEXT COLLATE "C",
    renovar_dias  INTEGER NOT NULL DEFAULT 120,
    unidade       TEXT COLLATE "C",
    ativo_codigo  TEXT COLLATE "C",
    arquivo       TEXT COLLATE "C",
    guardado_em   TEXT COLLATE "C",
    sha256        TEXT COLLATE "C",
    texto         TEXT,
    enviada_por   TEXT COLLATE "C" NOT NULL,
    enviada_em    TEXT COLLATE "C" NOT NULL,
    UNIQUE (empresa_id, tipo, numero)
);

-- Condicionante proposta pela IA com o trecho literal conferido pelo Python; quem aprova é o
-- Regulatório (ou a Diretoria) da própria empresa, e aprovada vira obrigação própria.
CREATE TABLE IF NOT EXISTS condicionante (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    licenca_id     BIGINT NOT NULL REFERENCES licenca(id),
    empresa_id     BIGINT NOT NULL REFERENCES empresa(id),
    titulo         TEXT COLLATE "C" NOT NULL,
    prazo          TEXT COLLATE "C",
    periodicidade  TEXT COLLATE "C",
    agenda         TEXT COLLATE "C",
    evidencia      TEXT COLLATE "C",
    aplica_a       TEXT COLLATE "C",
    alvo           TEXT COLLATE "C",
    trecho         TEXT NOT NULL,
    pagina         INTEGER,
    status         TEXT COLLATE "C" NOT NULL DEFAULT 'pendente',
    codigo         TEXT COLLATE "C",
    proposta_em    TEXT COLLATE "C" NOT NULL,
    decidida_por   TEXT COLLATE "C",
    decidida_em    TEXT COLLATE "C",
    nota           TEXT
);
CREATE INDEX IF NOT EXISTS condicionante_empresa ON condicionante(empresa_id, status);

-- Responsável técnico e coordenador do PAEBM. O CPF é dado pessoal: cifrado por campo
-- (mitra/pessoal.py), mascarado pela API, e ver o CPF inteiro vai para a auditoria.
CREATE TABLE IF NOT EXISTS responsavel_tecnico (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id        BIGINT NOT NULL REFERENCES empresa(id),
    papel             TEXT COLLATE "C" NOT NULL,
    nome              TEXT COLLATE "C" NOT NULL,
    cpf_cifrado       TEXT COLLATE "C",
    cpf_fim           TEXT COLLATE "C",
    registro          TEXT COLLATE "C",
    art_numero        TEXT COLLATE "C",
    art_vigencia_ate  TEXT COLLATE "C",
    unidade           TEXT COLLATE "C",
    ativo_codigo      TEXT COLLATE "C",
    consentimento     TEXT,
    ficticio          INTEGER NOT NULL DEFAULT 0,
    criado_por        TEXT COLLATE "C" NOT NULL,
    criado_em         TEXT COLLATE "C" NOT NULL
);
CREATE INDEX IF NOT EXISTS responsavel_tecnico_empresa ON responsavel_tecnico(empresa_id);

-- A empresa pode adiantar o prazo de uma obrigação sem mudar a norma: a torre mostra os dois.
CREATE TABLE IF NOT EXISTS prazo_interno (
    empresa_id    BIGINT NOT NULL REFERENCES empresa(id),
    codigo        TEXT COLLATE "C" NOT NULL,
    dias_antes    INTEGER NOT NULL,
    definido_por  TEXT COLLATE "C" NOT NULL,
    definido_em   TEXT COLLATE "C" NOT NULL,
    PRIMARY KEY (empresa_id, codigo)
);

-- Responsável padrão por área: obrigação nova da empresa já nasce com responsável.
CREATE TABLE IF NOT EXISTS responsavel_padrao (
    empresa_id    BIGINT NOT NULL REFERENCES empresa(id),
    area          TEXT COLLATE "C" NOT NULL,
    responsavel   TEXT COLLATE "C" NOT NULL,
    definido_por  TEXT COLLATE "C" NOT NULL,
    definido_em   TEXT COLLATE "C" NOT NULL,
    PRIMARY KEY (empresa_id, area)
);

-- O código da obrigação é único por empresa: COALESCE porque em SQL NULL não é igual a NULL.
CREATE UNIQUE INDEX IF NOT EXISTS obrigacao_empresa_codigo ON obrigacao (COALESCE(empresa, ''), codigo);
