-- Checklist da etapa 5 da instanciação (mitra/instanciacao.py): alvarás e exigências municipais da
-- sede e de cada unidade. IF NOT EXISTS: um banco criado pelo schema_pg.sql novo já tem a tabela.
CREATE TABLE IF NOT EXISTS exigencia_municipal (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id  BIGINT NOT NULL REFERENCES empresa(id),
    local       TEXT COLLATE "C" NOT NULL DEFAULT '',
    situacao    TEXT COLLATE "C" NOT NULL CHECK (situacao IN ('confirmado', 'nao_se_aplica')),
    nota        TEXT,
    por         TEXT COLLATE "C" NOT NULL,
    em          TEXT COLLATE "C" NOT NULL,
    UNIQUE (empresa_id, local)
);

