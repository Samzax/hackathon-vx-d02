-- Instanciação (regulaia/instanciacao.py): levar uma cliente nova do zero até a torre funcionando.
-- IF NOT EXISTS: um banco criado pelo schema_pg.sql novo (testes, primeiro start) já tem tudo.

-- a operação a que o ativo pertence ("Mina Serra Azul"): unidade.nome da mesma empresa
ALTER TABLE ativo ADD COLUMN IF NOT EXISTS unidade TEXT COLLATE "C";

-- senha provisória (a primeira conta da cliente): a pessoa troca no primeiro acesso
ALTER TABLE usuario ADD COLUMN IF NOT EXISTS trocar_senha INTEGER NOT NULL DEFAULT 0 CHECK (trocar_senha IN (0, 1));

-- escopo por unidade: JSON com os nomes das unidades que a conta vê; '[]' = todas as da empresa
-- (Diretoria e Regulatório da empresa continuam vendo tudo)
ALTER TABLE usuario ADD COLUMN IF NOT EXISTS unidades TEXT NOT NULL DEFAULT '[]';

-- Código da obrigação único por empresa, não global: duas clientes têm cada uma a sua "LO-01", e as
-- normas públicas (empresa vazia) continuam únicas entre si. O índice é sobre COALESCE(empresa, '')
-- porque em SQL NULL não é igual a NULL: sem o COALESCE, "OB-01" pública entraria duas vezes.
ALTER TABLE obrigacao DROP CONSTRAINT IF EXISTS obrigacao_codigo_key;
CREATE UNIQUE INDEX IF NOT EXISTS obrigacao_empresa_codigo ON obrigacao (COALESCE(empresa, ''), codigo);

-- Uma por empresa. O estado de cada etapa sai dos dados; quem fez o quê e quando fica em instanciacao_evento.
CREATE TABLE IF NOT EXISTS instanciacao (
    empresa_id    BIGINT PRIMARY KEY REFERENCES empresa(id),
    cnpj          TEXT COLLATE "C" UNIQUE,
    razao_social  TEXT COLLATE "C" NOT NULL,
    ufs           TEXT NOT NULL DEFAULT '[]',
    no_sigbm      INTEGER NOT NULL DEFAULT 0,
    criada_por    TEXT COLLATE "C" NOT NULL,
    criada_em     TEXT COLLATE "C" NOT NULL
);

CREATE TABLE IF NOT EXISTS instanciacao_evento (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id  BIGINT NOT NULL REFERENCES empresa(id),
    etapa       TEXT COLLATE "C" NOT NULL,
    acao        TEXT COLLATE "C" NOT NULL,
    detalhe     TEXT,
    por         TEXT COLLATE "C" NOT NULL,
    em          TEXT COLLATE "C" NOT NULL
);
CREATE INDEX IF NOT EXISTS instanciacao_evento_empresa ON instanciacao_evento(empresa_id, etapa);

-- A operação da empresa ("Mina Serra Azul", com as barragens e os equipamentos dela).
CREATE TABLE IF NOT EXISTS unidade (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id  BIGINT NOT NULL REFERENCES empresa(id),
    nome        TEXT COLLATE "C" NOT NULL,
    uf          TEXT COLLATE "C",
    municipio   TEXT COLLATE "C",
    criada_por  TEXT COLLATE "C",
    criada_em   TEXT COLLATE "C" NOT NULL,
    UNIQUE (empresa_id, nome)
);

-- A licença (LP, LI, LO, LAC, outorga, autorização) que a empresa enviou em PDF. O texto lido fica
-- aqui para o Python conferir, palavra por palavra, o trecho que a IA citou em cada condicionante.
CREATE TABLE IF NOT EXISTS licenca (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id    BIGINT NOT NULL REFERENCES empresa(id),
    tipo          TEXT COLLATE "C" NOT NULL,
    numero        TEXT COLLATE "C" NOT NULL,
    orgao         TEXT COLLATE "C",
    emitida_em    TEXT COLLATE "C",
    validade      TEXT COLLATE "C",                 -- AAAA-MM-DD: vira obrigação de renovação
    renovar_dias  INTEGER NOT NULL DEFAULT 120,     -- quantos dias antes do vencimento pedir a renovação
    unidade       TEXT COLLATE "C",                 -- a que unidade se aplica (vazio: a empresa)
    ativo_codigo  TEXT COLLATE "C",                 -- ou a um ativo
    arquivo       TEXT COLLATE "C",                 -- o nome que as pessoas veem
    guardado_em   TEXT COLLATE "C",                 -- onde o original ficou (pasta ou S3)
    sha256        TEXT COLLATE "C",
    texto         TEXT,                             -- o texto lido do PDF (conferência do trecho)
    enviada_por   TEXT COLLATE "C" NOT NULL,
    enviada_em    TEXT COLLATE "C" NOT NULL,
    UNIQUE (empresa_id, tipo, numero)
);

-- Condicionante proposta pela IA a partir da licença, com o trecho literal conferido pelo Python.
-- Fica pendente até o Regulatório (ou a Diretoria) da própria empresa aprovar; aprovada, vira
-- obrigação própria com `empresa` preenchida (obrigacao.codigo, único por empresa).
CREATE TABLE IF NOT EXISTS condicionante (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    licenca_id     BIGINT NOT NULL REFERENCES licenca(id),
    empresa_id     BIGINT NOT NULL REFERENCES empresa(id),
    titulo         TEXT COLLATE "C" NOT NULL,
    prazo          TEXT COLLATE "C",
    periodicidade  TEXT COLLATE "C",
    agenda         TEXT COLLATE "C",                -- a agenda que a torre usa (ver regulaia/agenda.py)
    evidencia      TEXT COLLATE "C",
    aplica_a       TEXT COLLATE "C",                -- unidade | ativo | empresa
    alvo           TEXT COLLATE "C",                -- o nome da unidade ou o código do ativo
    trecho         TEXT NOT NULL,                   -- literal, conferido no texto do PDF
    pagina         INTEGER,
    status         TEXT COLLATE "C" NOT NULL DEFAULT 'pendente',   -- pendente | aprovada | rejeitada
    codigo         TEXT COLLATE "C",                -- a obrigação criada na aprovação
    proposta_em    TEXT COLLATE "C" NOT NULL,
    decidida_por   TEXT COLLATE "C",
    decidida_em    TEXT COLLATE "C",
    nota           TEXT
);
CREATE INDEX IF NOT EXISTS condicionante_empresa ON condicionante(empresa_id, status);

-- Responsável técnico e coordenador do PAEBM, por unidade ou por ativo. O CPF é dado pessoal:
-- guardado cifrado por campo (regulaia/pessoal.py, chave em REGULAIA_CHAVE_DADOS, nunca no Git),
-- devolvido mascarado pela API, e cada visualização do CPF inteiro vai para a auditoria.
CREATE TABLE IF NOT EXISTS responsavel_tecnico (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id        BIGINT NOT NULL REFERENCES empresa(id),
    papel             TEXT COLLATE "C" NOT NULL,    -- responsavel_tecnico | coordenador_paebm | ...
    nome              TEXT COLLATE "C" NOT NULL,
    cpf_cifrado       TEXT COLLATE "C",             -- Fernet; nunca o CPF em claro
    cpf_fim           TEXT COLLATE "C",             -- os 4 dígitos do meio, para a máscara e a busca
    registro          TEXT COLLATE "C",             -- conselho (CREA MG-123456)
    art_numero        TEXT COLLATE "C",
    art_vigencia_ate  TEXT COLLATE "C",             -- ART vencendo vira obrigação
    unidade           TEXT COLLATE "C",
    ativo_codigo      TEXT COLLATE "C",
    consentimento     TEXT,                         -- JSON: quem, quando, para quê (empreendedor PF)
    ficticio          INTEGER NOT NULL DEFAULT 0,   -- na demo, só CPF fictício e marcado como tal
    criado_por        TEXT COLLATE "C" NOT NULL,
    criado_em         TEXT COLLATE "C" NOT NULL
);
CREATE INDEX IF NOT EXISTS responsavel_tecnico_empresa ON responsavel_tecnico(empresa_id);

-- Personalização: a empresa pode adiantar o prazo de uma obrigação (pública ou própria) sem mudar a
-- norma. A torre mostra os dois prazos (interno e legal) e atrasa pelo interno.
CREATE TABLE IF NOT EXISTS prazo_interno (
    empresa_id    BIGINT NOT NULL REFERENCES empresa(id),
    codigo        TEXT COLLATE "C" NOT NULL,
    dias_antes    INTEGER NOT NULL,
    definido_por  TEXT COLLATE "C" NOT NULL,
    definido_em   TEXT COLLATE "C" NOT NULL,
    PRIMARY KEY (empresa_id, codigo)
);

-- Responsável padrão por área: obrigação nova da empresa já nasce com responsável.
CREATE TABLE IF NOT EXISTS responsavel_padrao (
    empresa_id    BIGINT NOT NULL REFERENCES empresa(id),
    area          TEXT COLLATE "C" NOT NULL,
    responsavel   TEXT COLLATE "C" NOT NULL,
    definido_por  TEXT COLLATE "C" NOT NULL,
    definido_em   TEXT COLLATE "C" NOT NULL,
    PRIMARY KEY (empresa_id, area)
);
