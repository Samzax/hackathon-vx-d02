-- Resumo da análise de cada ato (candidatas, motivo, custo e mudanças propostas), que o cartão de
-- Mudanças mostra. Ficava em data/radar_demo.json, dentro do container: todo deploy apagava, e o cartão
-- perdia o porquê até alguém recriar a demo. IF NOT EXISTS: um banco criado pelo schema_pg.sql novo já
-- tem a tabela.
CREATE TABLE IF NOT EXISTS analise_ato (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ato       TEXT COLLATE "C" NOT NULL UNIQUE,
    registro  TEXT COLLATE "C" NOT NULL,
    em        TEXT COLLATE "C" NOT NULL DEFAULT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')
);
